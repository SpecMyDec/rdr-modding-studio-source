"""Does `bound_grp_fffffffffftf` spell out its own collision flags?

Collision nodes generated by the exporter are named things like

    bound_bound_grp_fffffffffftf_01

and there are exactly **12** `BoundFlag*` attributes on the disc, against
exactly **12** t/f characters in that name. If the name is the flag vector then
the order of the characters gives the canonical flag order -- which is worth
having, because it is the order the engine almost certainly packs them in.

This is a real test with a real chance of failing: it needs one consistent
character order that explains every such node on the disc, and there are
thousands of them across many levels.
"""
import re
import sys
from collections import Counter
from itertools import permutations
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from rdrstudio.game import Game                      # noqa: E402
from rdrstudio.level import Level                    # noqa: E402
from rdrstudio import config                         # noqa: E402

# The PRISTINE disc. This is a read-only structural check, so it must not
# baseline on the working copy -- that makes its result depend on whatever
# the last write left behind. Was a hardcoded `D:\...\RDR_MODDED.iso`,
# which also meant this only ran under Windows python. REQ-035.
DISC = Path(config.VANILLA_ISO)
NAME_RE = re.compile(r"_grp_([tf]+)", re.I)

FLAGS = ["BoundFlagPlayer", "BoundFlagEnemy", "BoundFlagHorse",
         "BoundFlagCamera", "BoundFlagCamClip", "BoundFlagTarget",
         "BoundFlagShoot", "BoundFlagMover", "BoundFlagSneak",
         "BoundFlagDoor", "BoundFlagWater", "BoundFlagPlummet"]


def main():
    game = Game(DISC, writable=False)
    rows = []
    for arc in [a for a in game.archives() if a.startswith("LVLS")]:
        try:
            lv = Level(game, arc)
        except Exception:
            continue
        for n in lv.nodes:
            m = NAME_RE.search(n.name)
            if not m:
                continue
            flags = {k[5:]: v for k, v in n.props.items()
                     if k.startswith("attr.BoundFlag")}
            if len(flags) != 12:
                continue
            rows.append((m.group(1).lower(), flags, n.name, arc))
    game.close()

    print("%d collision nodes whose name carries a t/f vector AND 12 flags"
          % len(rows))
    if not rows:
        print("none -- nothing to test")
        return 1

    lens = Counter(len(r[0]) for r in rows)
    print("name vector lengths: %s" % lens.most_common(5))
    rows = [r for r in rows if len(r[0]) == 12]
    print("%d with exactly 12 characters" % len(rows))
    if not rows:
        return 1

    # For each character position, find which flag it always agrees with.
    print("\nmatching each character position to a flag:")
    order = []
    ok = True
    for pos in range(12):
        chars = [r[0][pos] for r in rows]
        matches = []
        for f in FLAGS:
            vals = ["t" if str(r[1][f]).lower() == "true" else "f" for r in rows]
            agree = sum(1 for a, b in zip(chars, vals) if a == b)
            matches.append((agree / float(len(rows)), f))
        matches.sort(reverse=True)
        best, second = matches[0], matches[1]
        flag = best[1] if best[0] > 0.999 else None
        order.append(flag)
        print("  position %2d -> %-22s %.1f%%   (next best %s %.1f%%)"
              % (pos, flag or "NO EXACT MATCH", 100 * best[0],
                 second[1][9:], 100 * second[0]))
        if flag is None:
            ok = False

    if ok and len(set(order)) == 12:
        print("\nEVERY position maps to exactly one flag, on all %d nodes."
              % len(rows))
        print("The canonical BoundFlag order is:")
        for i, f in enumerate(order):
            print("   %2d  %s" % (i, f))
    else:
        print("\nThe name is NOT a clean flag vector in this order.")
        print("Positions without an exact match: %s"
              % [i for i, f in enumerate(order) if f is None])
        if len(set(order)) != 12:
            dup = [f for f, c in Counter(order).items() if c > 1 and f]
            print("Flags claimed by more than one position: %s" % dup)
        ok = False

    print("\n%s" % ("ALL CHECKS PASSED" if ok else "SOMETHING FAILED"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
